void HudRenderer::buildFontAtlas()
{
    // Pack 95 characters into a 16x6 grid of 8x8 cells => 128x48 texture.
    const int cols = 16, rows = 6;
    const int texW = cols * 8, texH = rows * 8;
    std::vector<unsigned char> pixels(texW * texH, 0);

    for (int ch = 0; ch < 95; ++ch)
    {
        int col = ch % cols;
        int row = ch / cols;
        for (int py = 0; py < 8; ++py)
        {
            unsigned char bits = g_font8x8[ch][py];
            for (int px = 0; px < 8; ++px)
            {
                int tx = col * 8 + px;
                int ty = row * 8 + py;
                pixels[ty * texW + tx] = (bits & (0x80 >> px)) ? 255 : 0;
            }
        }
    }

    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glGenTextures(1, &fontTexture);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, texW, texH, 0, GL_RED,
                 GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glBindTexture(GL_TEXTURE_2D, 0);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 4);
}

void HudRenderer::buildShader()
{
    const char* vs = R"(
        #version 330 core
        layout (location=0) in vec2 aPos;
        layout (location=1) in vec2 aUV;
        out vec2 uv;
        uniform mat4 ortho;
        void main() {
            uv = aUV;
            gl_Position = ortho * vec4(aPos, 0.0, 1.0);
        }
    )";
    const char* fs = R"(
        #version 330 core
        in vec2 uv;
        out vec4 FragColor;
        uniform sampler2D fontTex;
        uniform vec3 textColor;
        void main() {
            float a = texture(fontTex, uv).r;
            if (a < 0.5) discard;
            FragColor = vec4(textColor, a);
        }
    )";

    unsigned int v = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(v, 1, &vs, NULL);
    glCompileShader(v);
    unsigned int f = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(f, 1, &fs, NULL);
    glCompileShader(f);

    shaderID = glCreateProgram();
    glAttachShader(shaderID, v);
    glAttachShader(shaderID, f);
    glLinkProgram(shaderID);
    glDeleteShader(v);
    glDeleteShader(f);
}

void HudRenderer::Init(int w, int h)
{
    screenWidth = w;
    screenHeight = h;
    ortho = glm::ortho(0.0f, (float)w, (float)h, 0.0f); // top-left origin

    buildFontAtlas();
    buildShader();

    glGenVertexArrays(1, &VAO);
    glGenBuffers(1, &VBO);
    glBindVertexArray(VAO);
    glBindBuffer(GL_ARRAY_BUFFER, VBO);
    // We'll stream up to 1024 characters per RenderText call => 6 verts each
    glBufferData(GL_ARRAY_BUFFER, 1024 * 6 * 4 * sizeof(float), NULL, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)(2*sizeof(float)));
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);
}

void HudRenderer::Resize(int w, int h)
{
    screenWidth = w;
    screenHeight = h;
    ortho = glm::ortho(0.0f, (float)w, (float)h, 0.0f);
}

void HudRenderer::BeginFrame()
{
    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glUseProgram(shaderID);
    glUniformMatrix4fv(glGetUniformLocation(shaderID, "ortho"), 1, GL_FALSE,
                       &ortho[0][0]);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    glUniform1i(glGetUniformLocation(shaderID, "fontTex"), 0);
}

void HudRenderer::EndFrame()
{
    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);
}

void HudRenderer::RenderText(const std::string& text, float x, float y,
                              float scale, glm::vec3 color)
{
    glUniform3f(glGetUniformLocation(shaderID, "textColor"),
                color.r, color.g, color.b);

    const int cols = 16;
    const float cellU = 8.0f / 128.0f;
    const float cellV = 8.0f / 48.0f;
    const float glyphW = 8.0f * scale;
    const float glyphH = 8.0f * scale;

    std::vector<float> verts;
    verts.reserve(text.size() * 6 * 4);

    float cx = x;
    for (char c : text)
    {
        int idx = (int)c - 32;
        if (idx < 0 || idx >= 95) { cx += glyphW; continue; }

        int col = idx % cols;
        int row = idx / cols;
        float u0 = col * cellU;
        float v0 = row * cellV;
        float u1 = u0 + cellU;
        float v1 = v0 + cellV;

        float x0 = cx, x1 = cx + glyphW;
        float y0 = y,  y1 = y + glyphH;

        // Two triangles (6 vertices)
        verts.insert(verts.end(), {x0,y0, u0,v0});
        verts.insert(verts.end(), {x1,y0, u1,v0});
        verts.insert(verts.end(), {x0,y1, u0,v1});
        verts.insert(verts.end(), {x1,y0, u1,v0});
        verts.insert(verts.end(), {x1,y1, u1,v1});
        verts.insert(verts.end(), {x0,y1, u0,v1});

        cx += glyphW;
    }

    if (verts.empty()) return;

    glBindVertexArray(VAO);
    glBindBuffer(GL_ARRAY_BUFFER, VBO);
    glBufferSubData(GL_ARRAY_BUFFER, 0,
                    verts.size() * sizeof(float), verts.data());
    glDrawArrays(GL_TRIANGLES, 0, (int)(verts.size() / 4));
    glBindVertexArray(0);
}

void HudRenderer::RenderTextCentered(const std::string& text, float y,
                                      float scale, glm::vec3 color)
{
    float textW = text.size() * 8.0f * scale;
    float x = (screenWidth - textW) * 0.5f;
    RenderText(text, x, y, scale, color);
}
